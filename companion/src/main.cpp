namespace {

namespace fs = std::filesystem;
using midicomp::Theme;

/** Reloads the Bitwig theme when the theme editor's files change. */
class ThemeWatcher {
  public:
    explicit ThemeWatcher(fs::path editorDir) : editorDir_(std::move(editorDir)) { refresh(); }

    [[nodiscard]] const Theme::Sources& sources() const { return sources_; }

    /** Returns whether the theme files changed since the last call; checks at most once a second.
     */
    bool changed() {
        const auto now = std::chrono::steady_clock::now();
        if (now - lastCheck_ < std::chrono::seconds(1))
            return false;
        lastCheck_ = now;
        const auto before = stamps_;
        const auto beforeFiles = sources_.files;
        refresh();
        return stamps_ != before || sources_.files != beforeFiles;
    }

  private:
    void refresh() {
        sources_ = Theme::locate(editorDir_);
        stamps_.clear();
        std::vector<fs::path> files = sources_.files;
        files.push_back(editorDir_ / "bte_config.txt");
        for (const auto& file : files) {
            std::error_code ec;
            stamps_.push_back(fs::last_write_time(file, ec));
        }
    }

    fs::path editorDir_;
    Theme::Sources sources_;
    std::vector<fs::file_time_type> stamps_;
    std::chrono::steady_clock::time_point lastCheck_{};
};

struct Options {
    fs::path themeDir = Theme::defaultEditorDir();
    fs::path endpoint = midicomp::defaultEndpointPath();
    fs::path storeDir = midicomp::CompStore::defaultDir();
    std::optional<fs::path> screenshot;
    std::string demoKeyboard;
    std::optional<float> scale;
    bool openSavedComps = false;
    std::string demoSession;
};

void printUsage() {
    std::puts(
        "Usage: midicomp-companion [OPTIONS]\n"
        "\n"
        "  --theme-dir DIR    Bitwig Theme Editor directory (default ~/.bitwig-theme-editor)\n"
        "  --endpoint FILE    discovery file written by the extension\n"
        "                     (default ~/.midicomp/endpoint.json)\n"
        "  --store-dir DIR    where saved comps are kept\n"
        "  --screenshot FILE  render for a few seconds, save the window as PPM and exit\n"
        "  --demo-keyboard NAME  show NAME as the keyboard without opening MIDI (screenshots)\n"
        "  --scale FACTOR     UI scale on top of the display's, instead of the saved setting\n"
        "  --open-saved-comps open the list of saved comps (screenshots)\n"
        "  --demo-session ID  treat the saved comp of session ID as the current one "
        "(screenshots)\n"
        "\n"
        "Environment: MIDICOMP_FONT=path/to/font.ttf overrides the UI font.");
}

std::optional<Options> parseArgs(const int argc, char** argv) {
    Options options;
    for (int i = 1; i < argc; ++i) {
        const std::string_view arg = argv[i];
        const bool hasValue = i + 1 < argc;
        if (arg == "--theme-dir" && hasValue) {
            options.themeDir = argv[++i];
        } else if (arg == "--endpoint" && hasValue) {
            options.endpoint = argv[++i];
        } else if (arg == "--store-dir" && hasValue) {
            options.storeDir = argv[++i];
        } else if (arg == "--screenshot" && hasValue) {
            options.screenshot = argv[++i];
        } else if (arg == "--demo-keyboard" && hasValue) {
            options.demoKeyboard = argv[++i];
        } else if (arg == "--open-saved-comps") {
            options.openSavedComps = true;
        } else if (arg == "--demo-session" && hasValue) {
            options.demoSession = argv[++i];
        } else if (arg == "--scale" && hasValue) {
            const float value = std::strtof(argv[++i], nullptr);
            if (!(value >= 0.5f && value <= 4.0f)) {
                std::fputs("--scale must be between 0.5 and 4\n", stderr);
                return std::nullopt;
            }
            options.scale = value;
        } else {
            printUsage();
            return std::nullopt;
        }
    }
    return options;
}

std::optional<std::string> fontPath() {
    if (const char* env = std::getenv("MIDICOMP_FONT"); env != nullptr && fs::exists(env))
        return env;
#ifdef MIDICOMP_DEFAULT_FONT
    if (fs::exists(MIDICOMP_DEFAULT_FONT))
        return MIDICOMP_DEFAULT_FONT;
#endif
    return std::nullopt;
}

void loadFont(const float scale) {
    ImGuiIO& io = ImGui::GetIO();
    if (const auto path = fontPath()) {
        ImFontConfig config;
        config.OversampleH = 2;
        if (io.Fonts->AddFontFromFileTTF(path->c_str(), 14.0f * scale, &config) != nullptr)
            return;
        std::fprintf(stderr, "Could not load font %s; using the built-in font\n", path->c_str());
    }
#ifdef MIDICOMP_EMBEDDED_FONT
    // Compiled into the binary for platforms without a configured font file.
    ImFontConfig embedded;
    embedded.FontDataOwnedByAtlas = false;
    embedded.OversampleH = 2;
    if (io.Fonts->AddFontFromMemoryTTF(const_cast<unsigned char*>(midicomp_font_data),
                                       static_cast<int>(midicomp_font_size), 14.0f * scale,
                                       &embedded) != nullptr)
        return;
#endif
    ImFontConfig config;
    config.SizePixels = 13.0f * scale;
    io.Fonts->AddFontDefault(&config);
}

/**
 * Saves the current framebuffer as a binary PPM.
 *
 * Args:
 *     path: output file.
 *     width: framebuffer width in pixels.
 *     height: framebuffer height in pixels.
 *
 * Returns:
 *     Whether the file was written.
 */
bool saveScreenshot(const fs::path& path, const int width, const int height) {
    std::vector<unsigned char> pixels(static_cast<std::size_t>(width) *
                                      static_cast<std::size_t>(height) * 3);
    glPixelStorei(GL_PACK_ALIGNMENT, 1);
    glReadPixels(0, 0, width, height, GL_RGB, GL_UNSIGNED_BYTE, pixels.data());

    std::ofstream out(path, std::ios::binary);
    if (!out)
        return false;
    out << "P6\n" << width << ' ' << height << "\n255\n";
    // OpenGL rows run bottom-up; PPM rows run top-down.
    const auto rowBytes = static_cast<std::size_t>(width) * 3;
    for (int row = height - 1; row >= 0; --row)
        out.write(reinterpret_cast<const char*>(pixels.data()) +
                      static_cast<std::ptrdiff_t>(row) * static_cast<std::ptrdiff_t>(rowBytes),
                  static_cast<std::streamsize>(rowBytes));
    return static_cast<bool>(out);
}

/**
 * How large to draw the UI.
 *
 * ImGui works in window coordinates. On X11 and Windows these are pixels and the display's scale
 * has to be applied by the application; on macOS and Wayland GLFW scales the framebuffer instead,
 * and window coordinates are already logical. :meth:`ui` applies the display's scale once either
 * way, times the user's factor.
 */
struct Scaling {
    float content = 1.0f;      ///< The display's content scale.
    float framebuffer = 1.0f;  ///< Framebuffer pixels per window coordinate.
    float user = 1.0f;         ///< The user's factor (View > UI scale, or --scale).

    /** Returns the UI scale in window coordinates. */
    [[nodiscard]] float ui() const { return content / framebuffer * user; }
};

/** Reads the display's content scale and the framebuffer scale of ``window``. */
void measureDisplay(GLFWwindow* window, Scaling& scaling) {
    float x = 1.0f;
    float y = 1.0f;
    glfwGetWindowContentScale(window, &x, &y);
    scaling.content = x > 0.0f ? x : 1.0f;
    int windowWidth = 0;
    int windowHeight = 0;
    int pixelWidth = 0;
    int pixelHeight = 0;
    glfwGetWindowSize(window, &windowWidth, &windowHeight);
    glfwGetFramebufferSize(window, &pixelWidth, &pixelHeight);
    scaling.framebuffer = windowWidth > 0 && pixelWidth > 0
                              ? static_cast<float>(pixelWidth) / static_cast<float>(windowWidth)
                              : 1.0f;
}

fs::path settingsPath() {
    return midicomp::CompStore::defaultDir().parent_path() / "settings.json";
}

/** Set from GLFW's callback when the window moves to a display with another scale. */
std::atomic<bool> displayScaleChanged{false};

void applyTheme(const ThemeWatcher& watcher, midicomp::CompView& view, const float scale) {
    const Theme theme = Theme::load(watcher.sources());
    midicomp::applyStyle(theme, scale);
    view.setPalette(midicomp::makePalette(theme));
}

}  // namespace

int main(int argc, char** argv) {
    const auto options = parseArgs(argc, argv);
    if (!options)
        return 2;

    glfwSetErrorCallback([](const int code, const char* text) {
        std::fprintf(stderr, "GLFW error %d: %s\n", code, text);
    });
    if (glfwInit() == GLFW_FALSE)
        return 1;

    glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 3);
    glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 2);
    glfwWindowHint(GLFW_OPENGL_PROFILE, GLFW_OPENGL_CORE_PROFILE);
    glfwWindowHint(GLFW_OPENGL_FORWARD_COMPAT, GLFW_TRUE);
    GLFWwindow* window = glfwCreateWindow(1280, 760, "MIDI Comp", nullptr, nullptr);
    if (window == nullptr) {
        glfwTerminate();
        return 1;
    }
    glfwMakeContextCurrent(window);
    glfwSwapInterval(1);

    Scaling scaling;
    measureDisplay(window, scaling);
    // Screenshots use the defaults, not this machine's preferences.
    midicomp::Settings settings =
        options->screenshot ? midicomp::Settings{} : midicomp::loadSettings(settingsPath());
    scaling.user = options->scale.value_or(settings.uiScale);
    glfwSetWindowContentScaleCallback(window, [](GLFWwindow*, float, float) {
        displayScaleChanged = true;
        glfwPostEmptyEvent();
    });

    IMGUI_CHECKVERSION();
    ImGui::CreateContext();
    ImGui::GetIO().IniFilename = nullptr;
    // Screenshots should not show hover effects from wherever the pointer happens to be.
    if (options->screenshot)
        ImGui::GetIO().ConfigFlags |= ImGuiConfigFlags_NoMouse;

    midicomp::CompView view;
    view.setSettings(&settings, options->screenshot ? fs::path(options->storeDir / "settings.json")
                                                    : settingsPath());
    midicomp::CompStore store(options->storeDir);
    view.setStore(&store);
    // Rendered screenshots should not depend on the connected devices.
    std::unique_ptr<midicomp::MidiInput> midi;
    view.setDemoSession(options->demoSession);
    if (!options->demoKeyboard.empty()) {
        view.setDemoKeyboard(options->demoKeyboard);
    } else if (!options->screenshot) {
        midi = std::make_unique<midicomp::MidiInput>(
            midicomp::CompStore::defaultDir().parent_path() / "keyboard.txt",
            [] { glfwPostEmptyEvent(); });
        view.setMidi(midi.get());
    }
    ThemeWatcher watcher(options->themeDir);

    // Fonts are rasterized at framebuffer resolution and shown at the UI scale.
    const auto applyScaling = [&](const bool rebuildTexture) {
        ImGuiIO& io = ImGui::GetIO();
        io.Fonts->Clear();
        loadFont(scaling.ui() * scaling.framebuffer);
        io.FontGlobalScale = 1.0f / scaling.framebuffer;
        if (rebuildTexture) {
            ImGui_ImplOpenGL3_DestroyFontsTexture();
            ImGui_ImplOpenGL3_CreateFontsTexture();
        }
        applyTheme(watcher, view, scaling.ui());
        view.setUiScale(scaling.user);
    };
    applyScaling(false);

    // The default size is meant for a UI scale of 1; keep it on the screen.
    {
        float width = 1280.0f * scaling.ui();
        float height = 760.0f * scaling.ui();
        if (GLFWmonitor* monitor = glfwGetPrimaryMonitor(); monitor != nullptr) {
            int x = 0;
            int y = 0;
            int areaWidth = 0;
            int areaHeight = 0;
            glfwGetMonitorWorkarea(monitor, &x, &y, &areaWidth, &areaHeight);
            if (areaWidth > 0 && areaHeight > 0) {
                width = std::min(width, static_cast<float>(areaWidth));
                height = std::min(height, static_cast<float>(areaHeight));
            }
        }
        glfwSetWindowSize(window, static_cast<int>(width), static_cast<int>(height));
    }

    ImGui_ImplGlfw_InitForOpenGL(window, true);
    ImGui_ImplOpenGL3_Init("#version 150");

    {
        // The client's threads wake the UI loop; destroy it before GLFW shuts down.
        midicomp::ApiClient client(options->endpoint, [] { glfwPostEmptyEvent(); });
        // Previews play the comp through a virtual MIDI port (not for screenshots).
        std::unique_ptr<midicomp::PreviewPlayer> preview;
        if (!options->screenshot) {
            preview =
                std::make_unique<midicomp::PreviewPlayer>([&client] { return client.playhead(); });
            view.setPreviewPlayer(preview.get());
        }
        const auto started = std::chrono::steady_clock::now();

        while (glfwWindowShouldClose(window) == GLFW_FALSE) {
            if (view.animating())
                glfwPollEvents();
            else
                glfwWaitEventsTimeout(0.25);

            if (displayScaleChanged.exchange(false)) {
                measureDisplay(window, scaling);
                applyScaling(true);
            }
            if (const auto requested = view.takeUiScaleRequest()) {
                scaling.user = *requested;
                if (!options->scale) {
                    settings.uiScale = scaling.user;
                    midicomp::saveSettings(settingsPath(), settings);
                }
                applyScaling(true);
            }
            if (watcher.changed())
                applyTheme(watcher, view, scaling.ui());
            if (options->openSavedComps &&
                std::chrono::steady_clock::now() - started > std::chrono::seconds(1))
                view.openSavedComps();

            ImGui_ImplOpenGL3_NewFrame();
            ImGui_ImplGlfw_NewFrame();
            ImGui::NewFrame();

            const ImGuiViewport* viewport = ImGui::GetMainViewport();
            ImGui::SetNextWindowPos(viewport->WorkPos);
            ImGui::SetNextWindowSize(viewport->WorkSize);
            ImGui::Begin("MIDI Comp", nullptr,
                         ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_NoMove |
                             ImGuiWindowFlags_NoSavedSettings |
                             ImGuiWindowFlags_NoBringToFrontOnFocus);
            view.draw(client);
            ImGui::End();

            ImGui::Render();
            int width = 0;
            int height = 0;
            glfwGetFramebufferSize(window, &width, &height);
            glViewport(0, 0, width, height);
            const ImVec4 bg = ImGui::GetStyle().Colors[ImGuiCol_WindowBg];
            glClearColor(bg.x, bg.y, bg.z, 1.0f);
            glClear(GL_COLOR_BUFFER_BIT);
            ImGui_ImplOpenGL3_RenderDrawData(ImGui::GetDrawData());

            // Give the client time to fetch the state before capturing.
            if (options->screenshot &&
                std::chrono::steady_clock::now() - started > std::chrono::seconds(3)) {
                const bool saved = saveScreenshot(*options->screenshot, width, height);
                std::fprintf(stderr, "%s %s\n", saved ? "Saved" : "Could not save",
                             options->screenshot->string().c_str());
                glfwSetWindowShouldClose(window, GLFW_TRUE);
            }
            glfwSwapBuffers(window);
        }
        view.setPreviewPlayer(nullptr);
    }

    // Its driver thread wakes GLFW; close it first.
    view.setMidi(nullptr);
    midi.reset();

    ImGui_ImplOpenGL3_Shutdown();
    ImGui_ImplGlfw_Shutdown();
    ImGui::DestroyContext();
    glfwDestroyWindow(window);
    glfwTerminate();
    return 0;
}
